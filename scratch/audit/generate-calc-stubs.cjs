// Generates src/lib/tools/calculatorStubSlugs.ts — the set of calculator slugs that are
// tagged "live" in the registry but must NOT be sitemapped or surfaced in grids because
// they either (a) have no wired component in lazyComponents.tsx, or (b) their component
// file renders the generic "Value A" template stub.
// Run: node scratch/audit/generate-calc-stubs.cjs
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..", "..");

// 1. registry slugs + status
const regDir = path.join(ROOT, "src", "domains", "calculator", "registry");
const registry = new Map();
for (const f of fs.readdirSync(regDir)) {
  if (!f.endsWith(".ts")) continue;
  const src = fs.readFileSync(path.join(regDir, f), "utf8");
  const re = /slug:\s*"([^"]+)",[\s\S]*?status:\s*"(live|soon)"/g;
  let m;
  while ((m = re.exec(src))) registry.set(m[1], m[2]);
}

// 2. wired slugs in lazyComponents.tsx
const lazySrc = fs.readFileSync(path.join(ROOT, "src", "app", "calculator", "lazyComponents.tsx"), "utf8");
const wired = new Map(); // slug -> import path
const ire = /^\s+"([a-z0-9()_-]+)": \(\) => import\("([^"]+)"\)/gm;
let m;
while ((m = ire.exec(lazySrc))) {
  if (m[1].endsWith("_test")) continue; // test-only slugs stay excluded from sitemap
  wired.set(m[1], m[2]);
}

// 3. live but not wired
const liveNoComponent = [...registry.entries()]
  .filter(([slug, st]) => st === "live" && !wired.has(slug))
  .map(([slug]) => slug);

// 4. wired slugs whose component file contains the Value A template
const valueATemplate = [];
for (const [slug, imp] of wired) {
  const rel = imp.replace("@/", path.join(ROOT, "src") + path.sep).replace(/\//g, path.sep);
  const file = rel + ".tsx";
  let content;
  try {
    content = fs.readFileSync(file, "utf8");
  } catch {
    continue;
  }
  if (content.includes(">Value A</label>")) valueATemplate.push(slug);
}

const union = [...new Set([...liveNoComponent, ...valueATemplate])].sort();
const overlap = liveNoComponent.filter(s => valueATemplate.includes(s));

// 5. games wired slugs (from games/lazyComponents.tsx)
const gamesLazy = fs.readFileSync(path.join(ROOT, "src", "app", "games", "lazyComponents.tsx"), "utf8");
const gameWired = [];
const gre = /^\s+"([a-z0-9-]+)": \(\) => import/gm;
let gm;
while ((gm = gre.exec(gamesLazy))) gameWired.push(gm[1]);
gameWired.sort();

console.log("registry live:", [...registry.values()].filter(v => v === "live").length);
console.log("wired:", wired.size);
console.log("live but no component:", liveNoComponent.length);
console.log("Value-A template wired:", valueATemplate.length);
console.log("overlap:", overlap.length);
console.log("union (stub slugs to exclude):", union.length);
console.log("games wired (live):", gameWired.length);

const out = `// AUTO-GENERATED by scratch/audit/generate-calc-stubs.cjs — DO NOT EDIT BY HAND.
// Calculator slugs tagged "live" that render stub content (no wired component OR the
// generic "Value A" template UI). Excluded from sitemap and grid discovery until rebuilt.
export const CALCULATOR_STUB_SLUGS: string[] = ${JSON.stringify(union, null, 2)};
`;
fs.writeFileSync(path.join(ROOT, "src", "lib", "tools", "calculatorStubSlugs.ts"), out);

const gamesOut = `// AUTO-GENERATED by scratch/audit/generate-calc-stubs.cjs — DO NOT EDIT BY HAND.
// Game slugs with a wired component in src/app/games/lazyComponents.tsx.
// Only these are sitemapped / discoverable; all other game URLs render "Coming Soon".
export const GAME_LIVE_SLUGS: string[] = ${JSON.stringify(gameWired, null, 2)};
`;
fs.writeFileSync(path.join(ROOT, "src", "lib", "tools", "gameLiveSlugs.ts"), gamesOut);

console.log("wrote src/lib/tools/calculatorStubSlugs.ts with", union.length, "slugs");
console.log("wrote src/lib/tools/gameLiveSlugs.ts with", gameWired.length, "slugs");
