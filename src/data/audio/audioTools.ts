function slugify(name: string): string {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

export const audioCategories: AudioCategory[] = categoriesData.map((cat) => {
  const tools: AudioTool[] = cat.tools.map((tool) => {
    const id = slugify(tool.name);
    return {
      id,
      name: tool.name,
      description: tool.description,
      category: cat.name,
      categorySlug: cat.slug,
      comingSoon: id !== "mp3-converter",
      icon: tool.icon,
    };
  });
  return {
    name: cat.name,
    slug: cat.slug,
    count: tools.length,
    tools,
  };
});

export const allTools: AudioTool[] = audioCategories.flatMap((cat) => cat.tools);

export const totalToolCount = allTools.length;

