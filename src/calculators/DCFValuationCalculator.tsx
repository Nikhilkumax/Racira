interface VBResult { wacc: number; terminalValue: number; presentValue: number; intrinsicValue: number; upside: number; marginOfSafety: number; }
const DEFAULTS = { fcf: "850000000", growthRate: "8", terminalGrowthRate: "3", discountRate: "10", sharesOutstanding: "3200000000", currentPrice: "145", projectionYears: "10" };

function calculate(d: typeof DEFAULTS): VBResult {
  const fcf = parseFloat(d.fcf)||0, g = (parseFloat(d.growthRate)||0)/100;
  const tg = (parseFloat(d.terminalGrowthRate)||0)/100, r = (parseFloat(d.discountRate)||0)/100;
  const shares = parseFloat(d.sharesOutstanding)||1, price = parseFloat(d.currentPrice)||1;
  const yrs = parseInt(d.projectionYears)||10;
  let pv = 0, cf = fcf;
  for (let i = 1; i <= yrs; i++) { cf *= (1 + g); pv += cf / Math.pow(1 + r, i); }
  const lastCF = fcf * Math.pow(1 + g, yrs);
  const terminalValue = r > tg ? lastCF * (1 + tg) / (r - tg) : 0;
  const pvTerminal = terminalValue / Math.pow(1 + r, yrs);
  const presentValue = pv + pvTerminal;
  const intrinsicValue = presentValue / shares;
  const upside = price > 0 ? (intrinsicValue - price) / price * 100 : 0;
  const marginOfSafety = intrinsicValue > 0 ? (intrinsicValue - price) / intrinsicValue * 100 : 0;
  return { wacc: r * 100, terminalValue, presentValue, intrinsicValue, upside, marginOfSafety };
}

const fmtB = (n: number) => n >= 1e12 ? `$${(n/1e12).toFixed(2)}T` : n >= 1e9 ? `$${(n/1e9).toFixed(2)}B` : `$${(n/1e6).toFixed(0)}M`;
const fmtDol = (n: number) => `$${n.toFixed(2)}`;

