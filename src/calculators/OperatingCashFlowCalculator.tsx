"use client";

import { useState, useEffect } from "react";
import Breadcrumb from "@/components/Breadcrumb";
import AdPlaceholder from "@/components/AdPlaceholder";
import FAQSection from "@/components/FAQSection";
import PopularCalculators from "@/components/PopularCalculators";
import { RotateCcw, Calculator } from "lucide-react";
import { BarChart, Bar, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer, Cell, ReferenceLine } from "recharts";

const DEFAULTS = {
  netIncome: "200000",
  da: "40000",
  arChange: "10000", // positive means AR increased (cash outflow)
  inventoryChange: "15000", // positive means inventory increased (cash outflow)
  apChange: "8000", // positive means AP increased (cash inflow)
  otherNonCash: "5000"
};

interface OCFResult {
  ocf: number;
  qualityRatio: number | null;
  chartData: { name: string; value: number; fill: string }[];
}

function calculate(v: typeof DEFAULTS): OCFResult {
  const ni = parseFloat(v.netIncome) || 0;
  const dep = parseFloat(v.da) || 0;
  const ar = parseFloat(v.arChange) || 0;
  const inv = parseFloat(v.inventoryChange) || 0;
  const ap = parseFloat(v.apChange) || 0;
  const other = parseFloat(v.otherNonCash) || 0;

  // Operating Cash Flow = Net Income + D&A - AR Increase - Inv Increase + AP Increase + Other Non-Cash
  const ocf = ni + dep - ar - inv + ap + other;

  const qualityRatio = ni !== 0 ? ocf / ni : null;

  const chartData = [
    { name: "Net Income", value: ni, fill: "hsl(var(--primary))" },
    { name: "D&A (+)", value: dep, fill: "#10b981" },
    { name: "AR Increase (-)", value: -ar, fill: "#ef4444" },
    { name: "Inv Increase (-)", value: -inv, fill: "#f59e0b" },
    { name: "AP Increase (+)", value: ap, fill: "#6366f1" },
    { name: "Other Non-Cash (+)", value: other, fill: "#14b8a6" },
    { name: "OCF", value: ocf, fill: "#8b5cf6" }
  ];

  return { ocf, qualityRatio, chartData };
}

const fmtCurrency = (n: number) => {
  const abs = Math.abs(n);
  const formatted = new Intl.NumberFormat("en-US", {
    style: "currency",
    currency: "USD",
    maximumFractionDigits: 0
  }).format(abs);
  return n < 0 ? `-${formatted}` : formatted;
};

const fmtPct = (n: number) => `${(n * 100).toFixed(1)}%`;

