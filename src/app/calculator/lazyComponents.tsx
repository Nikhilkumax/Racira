// Pre-build lazy components at module level to avoid re-creating them on every render.
// Creating dynamic() inside a render function causes unnecessary remounting.
export const lazyComponents: Record<string, React.ComponentType> = Object.fromEntries(
  Object.entries(calculatorComponents).map(([slug, importFn]) => [
    slug,
    dynamic(importFn, { loading: () => <CalculatorSkeleton />, ssr: false }),
  ])
);


interface Props {
  params: { slug: string };
}

export async function generateStaticParams() {
  return calculatorRegistry.map((calc) => ({
    slug: calc.slug,
  }));
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const calc = getCalculatorBySlug(params.slug);
  if (!calc) return { title: "Calculator Not Found" };

  const title = `${calc.name} — Free Online Calculator`;
  const description = calc.description;
  const url = `https://racira.com/calculator/${params.slug}`;

  return {
    title,
    description,
    alternates: {
      canonical: url,
    },
    openGraph: {
      title,
      description,
      url,
      siteName: "Racira",
      type: "website",
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
    },
  };
}

export default function CalculatorPage({ params }: Props) {
  const { slug } = params;
  const calc = getCalculatorBySlug(slug);

  if (!calc) {
    notFound();
  }

  if (!calc.isBuilt) {
    return <ComingSoonCalculator slug={slug} />;
  }

  const CalculatorComponent = lazyComponents[slug];

  if (!CalculatorComponent) {
    return <ComingSoonCalculator slug={slug} />;
  }

  return (
    <Suspense fallback={<CalculatorSkeleton />}>
      <CalculatorComponent />
    </Suspense>
  );
}
