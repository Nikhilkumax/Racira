interface Props {
  params: { slug: string };
}

export async function generateStaticParams() {
  return calculatorRegistry.map((calc) => ({
    slug: calc.slug,
  }));
}

export async function generateMetadata({ params }: Props): Promise<Metadata> {
  const calc = getCalculatorBySlug(params.slug);
  if (!calc) return { title: "Calculator Not Found" };

  const title = `${calc.name} — Free Online Calculator`;
  const description = calc.description;
  const url = `https://racira.com/calculator/${params.slug}`;

  return {
    title,
    description,
    alternates: {
      canonical: url,
    },
    openGraph: {
      title,
      description,
      url,
      siteName: "Racira",
      type: "website",
    },
    twitter: {
      card: "summary_large_image",
      title,
      description,
    },
  };
}

export default function CalculatorPage({ params }: Props) {
  const { slug } = params;
  const calc = getCalculatorBySlug(slug);

  if (!calc) {
    notFound();
  }

  if (!calc.isBuilt) {
    return <ComingSoonPage slug={slug} />;
  }

  const importFn = calculatorComponents[slug];

  if (!importFn) {
    return <ComingSoonPage slug={slug} />;
  }

  const CalculatorComponent = dynamic(importFn, {
    loading: () => (
      <div className="flex min-h-[50vh] items-center justify-center text-muted-foreground">
        Loading Calculator...
      </div>
    ),
  });

  return (
    <Suspense fallback={<div>Loading...</div>}>
      <CalculatorComponent />
    </Suspense>
  );
}
