interface SequenceResult {
  sequenceType: string;
  formula: string;
  terms: number[];
  sum: number;
  chartData: { n: number; value: number }[];
  explanation: string[];
}

const analyzeSequence = (
  type: string,
  startTermStr: string,
  differenceOrRatioStr: string,
  numberOfTermsStr: string
): SequenceResult | null => {
  const a1 = parseFloat(startTermStr);
  const dOrR = parseFloat(differenceOrRatioStr);
  const n = parseInt(numberOfTermsStr, 10);

  if (isNaN(a1) || isNaN(dOrR) || isNaN(n) || n <= 0 || n > 1000) return null;

  const terms: number[] = [];
  const chartData: { n: number; value: number }[] = [];
  let sum = 0;
  let formula = "";
  let sequenceType = "";
  const explanation: string[] = [];

  if (type === "arithmetic") {
    sequenceType = "Arithmetic Sequence";
    formula = `aₙ = ${a1} + (n - 1) × ${dOrR}`;
    explanation.push(`An arithmetic sequence is generated by adding a constant difference (d = ${dOrR}) to each term.`);
    explanation.push(`The first term (a₁) is ${a1}.`);
    
    for (let i = 1; i <= n; i++) {
      const an = a1 + (i - 1) * dOrR;
      terms.push(an);
      sum += an;
      if (i <= 50) chartData.push({ n: i, value: an }); // limit chart data for performance
    }
    explanation.push(`The ${n}th term (aₙ) is ${terms[terms.length - 1]}.`);
    explanation.push(`The sum of the first ${n} terms (Sₙ) is ${sum}.`);

  } else if (type === "geometric") {
    sequenceType = "Geometric Sequence";
    formula = `aₙ = ${a1} × (${dOrR})^(n - 1)`;
    explanation.push(`A geometric sequence is generated by multiplying each term by a constant ratio (r = ${dOrR}).`);
    explanation.push(`The first term (a₁) is ${a1}.`);
    
    for (let i = 1; i <= n; i++) {
      const an = a1 * Math.pow(dOrR, i - 1);
      terms.push(an);
      sum += an;
      if (i <= 50) chartData.push({ n: i, value: an });
    }
    explanation.push(`The ${n}th term (aₙ) is ${terms[terms.length - 1]}.`);
    explanation.push(`The sum of the first ${n} terms (Sₙ) is ${sum}.`);

  } else if (type === "fibonacci") {
    sequenceType = "Fibonacci Sequence";
    formula = "Fₙ = Fₙ₋₁ + Fₙ₋₂";
    explanation.push(`The Fibonacci sequence is generated by adding the two previous terms together to get the next term.`);
    explanation.push(`(Note: Start Term and Diff/Ratio are ignored for standard Fibonacci)`);
    
    // Standard Fibonacci starting at 0, 1
    let f1 = 0, f2 = 1;
    for (let i = 1; i <= n; i++) {
      if (i === 1) {
        terms.push(f1);
        sum += f1;
        if (i <= 50) chartData.push({ n: i, value: f1 });
      } else if (i === 2) {
        terms.push(f2);
        sum += f2;
        if (i <= 50) chartData.push({ n: i, value: f2 });
      } else {
        const fn = f1 + f2;
        f1 = f2;
        f2 = fn;
        terms.push(fn);
        sum += fn;
        if (i <= 50) chartData.push({ n: i, value: fn });
      }
    }
    explanation.push(`The ${n}th term (Fₙ) is ${terms[terms.length - 1]}.`);
  } else {
    return null;
  }

  return { sequenceType, formula, terms, sum, chartData, explanation };
};

