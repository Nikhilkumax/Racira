"use client";

import { useState } from "react";
import Breadcrumb from "@/components/Breadcrumb";
import AdPlaceholder from "@/components/AdPlaceholder";
import PopularCalculators from "@/components/PopularCalculators";
import FAQSection from "@/components/FAQSection";
import InputField from "@/domains/calculator/components/ui/InputField";
import ResultDisplay from "@/domains/calculator/components/ui/ResultDisplay";
import PieChart from "@/domains/calculator/components/ui/PieChart";
import { RotateCcw, Share2, Leaf, Car, Plane, Home, Zap } from "lucide-react";

const CarbonFootprintCalculator = () => {
  // Home Energy
  const [electricity, setElectricity] = useState("300"); // kWh/month
  const [naturalGas, setNaturalGas] = useState("50"); // therms/month
  const [heatingOil, setHeatingOil] = useState("0"); // gallons/month

  // Transport
  const [carMiles, setCarMiles] = useState("1000"); // miles/month
  const [carMpg, setCarMpg] = useState("25"); 
  
  // Flights (Annual)
  const [shortFlights, setShortFlights] = useState("2"); // < 300 miles
  const [mediumFlights, setMediumFlights] = useState("1"); // 300-1500 miles
  const [longFlights, setLongFlights] = useState("0"); // > 1500 miles

  const [results, setResults] = useState<any>(null);
  const [showResults, setShowResults] = useState(false);

  const handleCalculate = () => {
    setShowResults(true);
    // Emission factors (kg CO2e)
    // Source: EPA / Carbon Trust / DEFRA approximate values
    const EF_ELEC = 0.4; // kg per kWh (average mix)
    const EF_GAS = 5.3; // kg per therm
    const EF_OIL = 10.1; // kg per gallon
    const EF_GASOLINE = 8.8; // kg per gallon
    
    // Flight factors (kg CO2e per passenger-trip)
    const EF_FLIGHT_SHORT = 150; 
    const EF_FLIGHT_MEDIUM = 400;
    const EF_FLIGHT_LONG = 1200;

    const houseCO2 = (parseFloat(electricity) * EF_ELEC * 12) +
                     (parseFloat(naturalGas) * EF_GAS * 12) +
                     (parseFloat(heatingOil) * EF_OIL * 12);

    const transportCO2 = ((parseFloat(carMiles) * 12) / (parseFloat(carMpg) || 1)) * EF_GASOLINE;

    const flightCO2 = (parseFloat(shortFlights) * EF_FLIGHT_SHORT) +
                     (parseFloat(mediumFlights) * EF_FLIGHT_MEDIUM) +
                     (parseFloat(longFlights) * EF_FLIGHT_LONG);

    const totalCO2 = houseCO2 + transportCO2 + flightCO2;
    const totalTons = totalCO2 / 1000; // metric tons

    setResults({
      totalTons,
      houseTons: houseCO2 / 1000,
      transportTons: transportCO2 / 1000,
      flightTons: flightCO2 / 1000,
      percentile: totalTons < 4 ? "Very Low" : totalTons < 10 ? "Average" : "High"
    });
  };

  const reset = () => {
    setShowResults(false);
    setElectricity("300"); setNaturalGas("50"); setHeatingOil("0");
    setCarMiles("1000"); setCarMpg("25");
    setShortFlights("2"); setMediumFlights("1"); setLongFlights("0");
    setResults(null);
  };

  const faqs = [
    { question: "What is a carbon footprint?", answer: "A carbon footprint is the total amount of greenhouse gases (including carbon dioxide and methane) that are generated by our actions. The average carbon footprint for a person in the United States is 16 tons, one of the highest rates in the world." },
    { question: "How can I reduce my carbon footprint?", answer: "Key ways include reducing energy consumption at home (insulation, LED bulbs), switching to a more fuel-efficient or electric vehicle, flying less, and eating a more plant-based diet." },
    { question: "What are carbon offsets?", answer: "Carbon offsets are contributions to projects that reduce greenhouse gas emissions, such as reforestation or renewable energy projects, intended to compensate for your own emissions." }
  ];

  return (
    <>
      <Breadcrumb items={[{ label: "Home", href: "/" }, { label: "Calculators", href: "/calculator" }, { label: "Carbon Footprint Calculator" }]} />
      <div className="racira-page-container py-4">
        <h1 className="text-3xl md:text-4xl font-bold mb-4 tracking-tight text-foreground">Carbon Footprint Calculator</h1>

        <div className="grid grid-cols-1 lg:grid-cols-[460px_1fr] gap-6 items-start max-w-[1180px]">
          <div className="card-calculator flex flex-col gap-3 !p-4 shadow-sm border border-border bg-card">
            <div className="space-y-8">
                {/* Home Energy Section */}
                <section>
                  <div className="flex items-center gap-2 mb-4 text-primary">
                    <Home className="h-5 w-5" />
                    <h2 className="text-2xl font-bold mb-3">Home Energy (Monthly)</h2>
                  </div>
                  <div className="grid sm:grid-cols-2 lg:grid-cols-3 gap-6">
                    <InputField id="elec" label="Electricity" value={electricity} onChange={setElectricity} suffix="kWh" />
                    <InputField id="gas" label="Natural Gas" value={naturalGas} onChange={setNaturalGas} suffix="therms" />
                    <InputField id="oil" label="Heating Oil" value={heatingOil} onChange={setHeatingOil} suffix="gal" />
                  </div>
                </section>

                {/* Transportation Section */}
                <section>
                  <div className="flex items-center gap-2 mb-4 text-primary">
                    <Car className="h-5 w-5" />
                    <h2 className="text-2xl font-bold mb-3">Transportation (Monthly)</h2>
                  </div>
                  <div className="grid sm:grid-cols-2 gap-6">
                    <InputField id="miles" label="Distance Driven" value={carMiles} onChange={setCarMiles} suffix="miles" />
                    <InputField id="mpg" label="Vehicle MPG" value={carMpg} onChange={setCarMpg} suffix="mpg" />
                  </div>
                </section>

                {/* Flights Section */}
                <section>
                  <div className="flex items-center gap-2 mb-4 text-primary">
                    <Plane className="h-5 w-5" />
                    <h2 className="text-2xl font-bold mb-3">Flights (Annual)</h2>
                  </div>
                  <div className="grid sm:grid-cols-2 lg:grid-cols-3 gap-6">
                    <InputField id="short" label="Short Haul (< 3hr)" value={shortFlights} onChange={setShortFlights} />
                    <InputField id="medium" label="Medium Haul (3-6hr)" value={mediumFlights} onChange={setMediumFlights} />
                    <InputField id="long" label="Long Haul (> 6hr)" value={longFlights} onChange={setLongFlights} />
                  </div>
                </section>
              </div>

              <div className="flex gap-3 mt-8">
                <button onClick={handleCalculate} className="btn-calculate flex-1 flex items-center justify-center gap-2">
                  <Leaf className="h-5 w-5" /> Calculate Footprint
                </button><button onClick={reset} className="p-3 rounded-xl border border-border hover:bg-secondary transition-colors text-muted-foreground">
                  <RotateCcw className="h-5 w-5" />
                </button>
              </div>
          </div>

          <div className="flex flex-col gap-3">
            {showResults && results && (
              <>
                <h2 className="text-2xl font-bold mb-3">Your Annual Impact</h2>
                <div className="grid sm:grid-cols-2 gap-6 mb-8">
                  <div className="p-6 rounded-2xl bg-primary/5 border border-primary/10 text-center">
                    <p className="text-sm font-bold text-primary uppercase tracking-widest mb-1">Total CO2e Emissions</p>
                    <p className="text-5xl font-black text-foreground">{results.totalTons.toFixed(1)} <span className="text-xl font-normal text-muted-foreground">Tons</span></p>
                  </div>
                  <div className="p-6 rounded-2xl bg-secondary/5 border border-secondary/10 text-center flex flex-col justify-center">
                    <p className="text-sm font-bold text-muted-foreground uppercase tracking-widest mb-1">Impact Level</p>
                    <p className="text-3xl font-black text-foreground">{results.percentile}</p>
                  </div>
                </div>

                <div className="grid md:grid-cols-2 gap-8 items-center">
                  <ResultDisplay items={[
                    { label: "Home Energy", value: 0, textValue: results.houseTons.toFixed(2) + " tons" },
                    { label: "Driving", value: 0, textValue: results.transportTons.toFixed(2) + " tons" },
                    { label: "Flights", value: 0, textValue: results.flightTons.toFixed(2) + " tons" },
                  ]} />
                  <div className="flex justify-center">
                    <PieChart
                      segments={[
                        { label: "Home", value: results.houseTons, color: "hsl(211, 100%, 50%)" },
                        { label: "Car", value: results.transportTons, color: "hsl(142, 70%, 45%)" },
                        { label: "Flights", value: results.flightTons, color: "hsl(47, 95%, 50%)" },
                      ]}
                      size={180}
                    />
                  </div>
                </div>
              </>
            )}
          </div>
        </div>

        <div className="max-w-[1180px] mt-8">
          <AdPlaceholder className="mb-10" />
          <article className="prose-finance text-[15.75px]">
              <h2 className="text-2xl font-bold mb-3">The Global Challenge</h2>
              <p>To avoid the worst effects of climate change, the average global carbon footprint per year needs to drop to under 2 tons by 2050. Currently, the global average is closer to 4 tons per person.</p>
              <h3>Why Small Changes Matter</h3>
              <p>While large-scale systemic change is necessary, individual actions aggregate to significant impacts. For example, switching to LED lighting in your entire home can save over 500kg of CO2 per year, which is more than many short-haul flights.</p>
              <h3>Understanding Emission Factors</h3>
              <p>Our calculator uses average emission factors. For instance, the CO2 impact of electricity depends heavily on your local grid's energy mix (coal vs. wind/solar). If you use 100% renewable energy, your Home Energy footprint would be significantly lower than shown here.</p>
            </article>
          <FAQSection faqs={faqs} pageUrl="https://racira.com/calculator/carbon-footprint" />
          <PopularCalculators exclude="/calculator/carbon-footprint-calculator" />
        </div>
      </div>
    </>
  );
};

export default CarbonFootprintCalculator;

