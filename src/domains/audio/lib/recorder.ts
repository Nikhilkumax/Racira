/**
 * Recorder support DSP — pure, Node-verified.
 *
 *   padOrTrim      — force a recorded layer to the exact loop length
 *                    (pad with silence at the end, hard-trim overshoot).
 *   mixLoopLayers  — sum aligned layers into the loop mix; reports the peak
 *                    so the UI can warn before clipping on playback.
 *   cueText        — chapter timestamps as a standard CUE sheet (INDEX
 *                    MM:SS:ff, 75 fps frames) for podcast export.
 *   formatStamp    — human-readable HH:MM:SS.mmm stamp.
 */

export function padOrTrim(layer: Float32Array, loopLen: number): Float32Array {
  if (layer.length === loopLen) return layer;
  const out = new Float32Array(loopLen);
  const n = Math.min(layer.length, loopLen);
  for (let i = 0; i < n; i++) out[i] = layer[i];
  return out;
}

export interface LoopMixResult {
  /** Mixed loop, one Float32Array per channel. */
  channels: Float32Array[];
  /** Peak absolute sample across the mix (for clip warning). */
  peak: number;
  /** Loop length in samples. */
  loopLen: number;
  /** Number of layers summed (excluding silent padding contributions). */
  layers: number;
}

/**
 * Sum loop takes, take-major: `takes[t][c]` = take t, channel c (mono takes
 * pass one channel; each channel is aligned to the loop with padOrTrim).
 * No limiting applied — the mix is honest; callers decide what to do with
 * `peak` (typically warn > 0.99).
 */
export function mixLoopLayers(takes: Float32Array[][], loopLen: number): LoopMixResult {
  const nCh = takes.reduce((m, t) => Math.max(m, t.length), 0);
  const channels: Float32Array[] = Array.from({ length: nCh }, () => new Float32Array(loopLen));
  for (const take of takes) {
    if (take.length === 1 && nCh > 1) {
      // mono take feeds every channel of the loop (mono-compatible by design)
      const aligned = padOrTrim(take[0], loopLen);
      for (let c = 0; c < nCh; c++) {
        for (let i = 0; i < loopLen; i++) channels[c][i] += aligned[i];
      }
    } else {
      for (let c = 0; c < take.length; c++) {
        const aligned = padOrTrim(take[c], loopLen);
        for (let i = 0; i < loopLen; i++) channels[c][i] += aligned[i];
      }
    }
  }
  let peak = 0;
  for (const ch of channels) {
    for (let i = 0; i < ch.length; i++) peak = Math.max(peak, Math.abs(ch[i]));
  }
  return { channels, peak, loopLen, layers: takes.length };
}

// ---------------------------------------------------------------------------
// Chapter / CUE export
// ---------------------------------------------------------------------------

export interface Chapter {
  /** Seconds from recording start. */
  t: number;
  name: string;
}

/** MM:SS:ff stamp (75 fps frames) as required by CUE INDEX lines. */
export function cueStamp(sec: number): string {
  const total = Math.max(0, sec);
  const mm = Math.floor(total / 60);
  const ss = Math.floor(total % 60);
  const ff = Math.floor((total - Math.floor(total)) * 75);
  const p2 = (n: number) => String(n).padStart(2, "0");
  return `${p2(mm)}:${p2(ss)}:${p2(ff)}`;
}

/** HH:MM:SS.mmm human stamp. */
export function formatStamp(sec: number): string {
  const total = Math.max(0, sec);
  const hh = Math.floor(total / 3600);
  const mm = Math.floor((total % 3600) / 60);
  const ss = Math.floor(total % 60);
  const mmm = Math.floor((total - Math.floor(total)) * 1000);
  const p2 = (n: number) => String(n).padStart(2, "0");
  return `${p2(hh)}:${p2(mm)}:${p2(ss)}.${String(mmm).padStart(3, "0")}`;
}

/**
 * Standard CUE sheet with one TRACK per chapter (TRACK 01 = the file start
 * convention; chapter N becomes TRACK N+1 when the first chapter is at 0).
 * Starts the file with a REM header noting the generator.
 */
export function cueText(fileName: string, chapters: Chapter[]): string {
  const lines: string[] = [];
  lines.push(`REM GENERATED BY RACIRA AUDIO RECORDER`);
  lines.push(`FILE "${fileName}" WAVE`);
  const list = [...chapters].sort((a, b) => a.t - b.t);
  const offset = list.length > 0 && Math.abs(list[0].t) < 0.001 ? 0 : 1;
  if (offset === 1) {
    lines.push(`  TRACK 01 AUDIO`);
    lines.push(`    INDEX 01 00:00:00`);
  }
  list.forEach((ch, i) => {
    const trackNo = String(i + 1 + offset).padStart(2, "0");
    lines.push(`  TRACK ${trackNo} AUDIO`);
    lines.push(`    TITLE "${ch.name.replace(/"/g, "'")}"`);
    lines.push(`    INDEX 01 ${cueStamp(ch.t)}`);
  });
  return lines.join("\n") + "\n";
}
