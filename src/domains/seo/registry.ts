export const slugify = (s: string) =>
  s
    .toLowerCase()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");

export const CATEGORIES: Category[] = raw.map((c) => ({
  name: c.category,
  slug: slugify(c.category),
  tools: c.tools,
}));

const seen = new Set<string>();
export const TOOLS: Tool[] = raw.flatMap((c) =>
  c.tools.map((name) => {
    let slug = slugify(name);
    while (seen.has(slug)) slug += "-2";
    seen.add(slug);
    return {
      slug,
      name,
      category: c.category,
      active: slug === "keyword-density-checker",
    };
  })
);

export const TOOL_BY_SLUG = new Map(TOOLS.map((t) => [t.slug, t]));
export const TOOLS_BY_CATEGORY = (cat: string) =>
  TOOLS.filter((t) => t.category === cat);

export const TOTAL_TOOLS = TOOLS.length;
