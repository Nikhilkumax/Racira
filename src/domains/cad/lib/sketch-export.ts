"use client";

/**
 * sketch-export.ts — DXF / SVG export for the CAD sketch tool, via Maker.js.
 *
 * Coordinate conventions (single source of truth):
 *  - The canvas model is px, Y-down (screen space). 1 grid cell = 20px = 10mm,
 *    so mm = px × 0.5.
 *  - DXF is a Y-UP world format (AutoCAD convention). To make the exported
 *    drawing appear exactly as it does on screen, Y is flipped when mapping to
 *    the Maker.js model: Y_mm = (canvasH_px − y_px) × 0.5.
 *  - SVG path data from Maker.js's toSVGPathData() negates model Y (it treats
 *    models as Y-up and renders Y-down). We therefore feed it model y = −y_screen,
 *    so the returned path data carries plain positive screen-space mm.
 *
 * Only `toDXF()` and `toSVGPathData()` (the path-data core of `toSVG()`) are
 * used. The default `toSVG()` re-origins and merges every path into one
 * transformed `<path>`, which makes coordinate round-trip verification
 * impossible; `toSVGPathData(model, { origin: [0, 0] })` emits raw coordinates.
 * Maker.js's PDF export takes a caller-supplied PDFKit document and @jscad is
 * never required, so neither ends up in the client bundle.
 */
import * as makerjs from "makerjs";

export type Pt = { x: number; y: number };

export type Shape =
  | { id: string; type: "line"; a: Pt; b: Pt }
  | { id: string; type: "rect"; a: Pt; b: Pt }
  | { id: string; type: "circle"; c: Pt; r: number }
  | { id: string; type: "polyline"; pts: Pt[] };

const MM_PER_PX = 0.5;

type MakerPath =
  | { type: "line"; origin: [number, number]; end: [number, number] }
  | { type: "circle"; origin: [number, number]; radius: number };

/** Screen px → DXF model mm with Y-up flip. */
const toCadMm = (p: Pt, canvasH: number): [number, number] => [
  p.x * MM_PER_PX,
  (canvasH - p.y) * MM_PER_PX,
];

/** Screen px → SVG model mm (y negated so path data comes back Y-down). */
const toSvgModelMm = (p: Pt): [number, number] => [
  p.x * MM_PER_PX,
  -p.y * MM_PER_PX,
];

/** Decompose a sketch shape into primitive Maker.js paths (rect → 4 lines). */
function shapeToPaths(s: Shape, toMm: (p: Pt) => [number, number]): MakerPath[] {
  if (s.type === "line") {
    return [{ type: "line", origin: toMm(s.a), end: toMm(s.b) }];
  }
  if (s.type === "circle") {
    return [{ type: "circle", origin: toMm(s.c), radius: s.r * MM_PER_PX }];
  }
  if (s.type === "rect") {
    const x0 = Math.min(s.a.x, s.b.x), x1 = Math.max(s.a.x, s.b.x);
    const y0 = Math.min(s.a.y, s.b.y), y1 = Math.max(s.a.y, s.b.y);
    const tl = toMm({ x: x0, y: y0 });
    const tr = toMm({ x: x1, y: y0 });
    const br = toMm({ x: x1, y: y1 });
    const bl = toMm({ x: x0, y: y1 });
    return [
      { type: "line", origin: tl, end: tr },
      { type: "line", origin: tr, end: br },
      { type: "line", origin: br, end: bl },
      { type: "line", origin: bl, end: tl },
    ];
  }
  // Polyline → one line path per segment.
  const out: MakerPath[] = [];
  for (let i = 0; i < s.pts.length - 1; i++) {
    out.push({ type: "line", origin: toMm(s.pts[i]), end: toMm(s.pts[i + 1]) });
  }
  return out;
}

function toModel(shapes: Shape[], toMm: (p: Pt) => [number, number]): makerjs.IModel {
  const paths: Record<string, MakerPath> = {};
  let n = 0;
  for (const s of shapes) {
    for (const p of shapeToPaths(s, toMm)) {
      paths[`p${n++}`] = p;
    }
  }
  return { units: makerjs.unitType.Millimeter, paths };
}

/** All extreme points of a shape in screen px (for SVG extents). */
function shapePoints(s: Shape): Pt[] {
  if (s.type === "line") return [s.a, s.b];
  if (s.type === "rect") return [s.a, s.b];
  if (s.type === "circle") return [s.c];
  return s.pts;
}

/** Export the sketch as DXF text (mm, Y-up so it opens correctly in CAD apps). */
export function exportDxf(shapes: Shape[], canvasH: number): string {
  const model = toModel(shapes, (p) => toCadMm(p, canvasH));
  return makerjs.exporter.toDXF(model, { units: makerjs.unitType.Millimeter });
}

/**
 * Export the sketch as an SVG string (mm, Y-down screen convention so it opens
 * the right way up in browsers/Illustrator). Path data is generated by
 * Maker.js's toSVGPathData; only the wrapper element is assembled here.
 */
export function exportSvg(shapes: Shape[]): string {
  const model = toModel(shapes, toSvgModelMm);
  const d = makerjs.exporter.toSVGPathData(model, { origin: [0, 0] }) as string;

  let maxX = 0;
  let maxY = 0;
  for (const s of shapes) {
    for (const p of shapePoints(s)) {
      maxX = Math.max(maxX, p.x * MM_PER_PX);
      maxY = Math.max(maxY, p.y * MM_PER_PX);
    }
    if (s.type === "circle") maxX = Math.max(maxX, (s.c.x + s.r) * MM_PER_PX);
  }

  const pad = 2; // mm breathing room so edge strokes aren't clipped
  const w = maxX + pad * 2;
  const h = maxY + pad * 2;
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" width="${w}mm" height="${h}mm" viewBox="0 0 ${w} ${h}">` +
    `<g transform="translate(${pad} ${pad})" fill="none" stroke="#000000" stroke-width="0.25mm" stroke-linecap="round" stroke-linejoin="round">` +
    `<path d="${d}"/>` +
    `</g></svg>`
  );
}
