/**
 * Generate src/domains/pdf/registry/implementedSlugs.ts from the audit CSV.
 *
 * Re-run after any audit changes:
 *   npx tsx scripts/audit-pdf-tools.ts   # regenerate CSVs
 *   npx tsx scripts/gen-implemented-slugs.ts  # regenerate this set
 */
import { readFileSync, writeFileSync } from 'fs';

const csv = readFileSync('scratch/audit/pdf-audit-final.csv', 'utf-8');
const lines = csv.split('\n').filter(l => l.trim());

const implemented: string[] = [];
for (let i = 1; i < lines.length; i++) {
  const m = lines[i].match(/^"([^"]+)","[^"]*","(Working[^"]*)"/);
  if (m && m[2].startsWith('Working')) {
    implemented.push(m[1]);
  }
}

implemented.sort();

const out = `/**
 * Auto-generated by scripts/gen-implemented-slugs.ts
 * Source: scratch/audit/pdf-audit-final.csv
 *
 * To regenerate after audit changes:
 *   npx tsx scripts/audit-pdf-tools.ts
 *   npx tsx scripts/gen-implemented-slugs.ts
 *
 * These are slugs with real implementation logic (engine_tag != "none")
 * regardless of their current registry status (live or soon).
 * Used by the dev-mode gate: stubs show ComingSoonView even in dev;
 * implemented tools show the real ToolPage in dev.
 */
export const IMPLEMENTED_SLUGS = new Set<string>([
${implemented.map(s => `  "${s}",`).join('\n')}
]);
`;

writeFileSync('src/domains/pdf/registry/implementedSlugs.ts', out);
console.log(`Wrote ${implemented.length} implemented slugs to src/domains/pdf/registry/implementedSlugs.ts`);
